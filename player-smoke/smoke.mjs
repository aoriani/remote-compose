import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { createProofServer, root } from './server.mjs';

const binary = resolve(process.argv[2] || resolve(root, 'artifacts/minimal-canvas.rc'));
const server = createProofServer(binary);
let browser;
try {
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  browser = await chromium.launch({
    channel: process.env.CHROME_CHANNEL || 'chrome',
    headless: true,
  });
  const page = await browser.newPage({viewport: {width: 600, height: 1200}, deviceScaleFactor: 1});
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => {
    if (message.type() === 'error' || /unknown operation opcode/i.test(message.text())) {
      errors.push(message.text());
    }
  });
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.waitForFunction(() => window.proof?.ready || window.proof?.error);
  const proof = await page.evaluate(() => window.proof);
  assert.equal(proof.error, null);
  const expected = createHash('sha256').update(await readFile(binary)).digest('hex');
  assert.equal(proof.sha256, expected, 'Browser must load the exact JVM-generated bytes');
  const pixel = (x, y) => page.evaluate(([x, y]) =>
    Array.from(document.querySelector('canvas').getContext('2d').getImageData(x, y, 1, 1).data), [x, y]);
  assert.deepEqual(await pixel(195, 160), [0, 103, 160, 255], 'Circle center has upstream paint color');
  assert.deepEqual(await pixel(195, 100), [0, 103, 160, 255], 'Point inside radius is painted');
  assert.deepEqual(await pixel(195, 80), [0, 0, 0, 0], 'Point outside radius stays transparent');
  assert.deepEqual(errors, []);
  await page.locator('canvas').screenshot({path: resolve(root, 'artifacts/browser-minimal.png')});
  const report = {player: 'experimental RcdPlayer', ...proof, browser: browser.version(), pixelChecks: 3};
  await writeFile(resolve(root, 'artifacts/browser-proof.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
} finally {
  if (browser) await browser.close();
  await new Promise(resolve => server.close(resolve));
}
